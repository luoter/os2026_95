// alloc_proc - 分配一个进程控制块并初始化为安全空白状态
static struct proc_struct *
alloc_proc(void)
{
    struct proc_struct *proc = kmalloc(sizeof(struct proc_struct));
    if (proc != NULL)
    {
        proc->state = PROC_UNINIT;
        proc->pid = -1;
        proc->runs = 0;
        proc->kstack = 0;
        proc->need_resched = 0;
        proc->parent = NULL;
        proc->mm = NULL;
        memset(&(proc->context), 0, sizeof(struct context));
        proc->tf = NULL;
        proc->pgdir = boot_pgdir_pa;
        proc->flags = 0;
        memset(proc->name, 0, sizeof(proc->name));
    }
    return proc;
}

// cpu_idle - 没有可运行进程时，idle 进程循环触发调度
void cpu_idle(void)
{
    while (1)
    {
        if (current->need_resched)
        {
            schedule();
        }
    }
}

// proc_run - 切换页表并把 CPU 执行权交给目标进程
void proc_run(struct proc_struct *proc)
{
    if (proc == current)
    {
        return;
    }

    bool intr_flag;
    local_intr_save(intr_flag);
    struct proc_struct *prev = current;
    current = proc;

    write_csr(satp, ((uintptr_t)SATP_MODE_SV39 << 60) |
                        (proc->pgdir >> RISCV_PGSHIFT));
    flush_tlb();
    switch_to(&prev->context, &proc->context);

    // This thread resumes here when another thread switches back to it.
    local_intr_restore(intr_flag);
}

